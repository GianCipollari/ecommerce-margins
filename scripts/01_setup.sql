USE ROLE ACCOUNTADMIN;

CREATE WAREHOUSE IF NOT EXISTS WH_MARGINS
  WAREHOUSE_SIZE = 'XSMALL'
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;

CREATE DATABASE IF NOT EXISTS ECOM_MARGINS;
CREATE SCHEMA IF NOT EXISTS ECOM_MARGINS.RAW;

CREATE RESOURCE MONITOR IF NOT EXISTS RM_MARGINS
  WITH CREDIT_QUOTA = 10
  TRIGGERS ON 80 PERCENT DO NOTIFY
           ON 100 PERCENT DO SUSPEND;

ALTER WAREHOUSE WH_MARGINS SET RESOURCE_MONITOR = RM_MARGINS;

SHOW WAREHOUSES LIKE 'WH_MARGINS';
SHOW RESOURCE MONITORS;