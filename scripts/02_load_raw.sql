USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_MARGINS;
USE SCHEMA ECOM_MARGINS.RAW;

-- 1. File format y stage
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_MARGINS;
USE SCHEMA ECOM_MARGINS.RAW;

CREATE OR REPLACE FILE FORMAT FF_OLIST_CSV
  TYPE = CSV
  PARSE_HEADER = TRUE
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  NULL_IF = ('');

CREATE OR REPLACE STAGE OLIST_STAGE FILE_FORMAT = FF_OLIST_CSV;

-- 2. Tablas y carga
USE ROLE ACCOUNTADMIN;
USE WAREHOUSE WH_MARGINS;
USE SCHEMA ECOM_MARGINS.RAW;
-- ORDERS
CREATE OR REPLACE TABLE ORDERS USING TEMPLATE (
  SELECT ARRAY_AGG(OBJECT_CONSTRUCT('COLUMN_NAME', UPPER(COLUMN_NAME), 'TYPE', TYPE, 'NULLABLE', NULLABLE))
         WITHIN GROUP (ORDER BY ORDER_ID)
  FROM TABLE(INFER_SCHEMA(LOCATION => '@OLIST_STAGE/olist_orders_dataset', FILE_FORMAT => 'FF_OLIST_CSV')));
COPY INTO ORDERS FROM @OLIST_STAGE/olist_orders_dataset MATCH_BY_COLUMN_NAME = CASE_INSENSITIVE;

